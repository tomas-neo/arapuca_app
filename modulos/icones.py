ICONE_MOTIVO = {"prato": "talheres", "funcao": "brilho", "passeio": "pata", "outro": "alerta"}


def icone(nome, classe=""):
    caminho = ICONES.get(nome, ICONES["lista"])
    return Markup(
        f'<svg class="ic {classe}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.8" '
        f'stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">{caminho}</svg>'
    )


def icone_escala(nome):
    """Escolhe o ícone pelo nome da escala (limpeza, passeio, roupa...)."""
    nome = (nome or "").lower()
    if "buddha" in nome or "passeio" in nome or "cachorro" in nome:
        return "pata"
    if "roupa" in nome or "lavar" in nome:
        return "camisa"
    if "limp" in nome or "lixo" in nome or "faxina" in nome:
        return "brilho"
    return "lista"


def avatar(morador_id, apelido, foto_versao=0, classe=""):
    """Foto do morador, ou a inicial do apelido num círculo quando não tem foto."""
    from flask import url_for
    from markupsafe import escape
    if foto_versao:
        src = url_for("auth.foto", morador_id=morador_id, v=foto_versao)
        return Markup(f'<img src="{src}" alt="" class="foto {classe}">')
    inicial = escape((apelido or "?")[:1].upper())
    return Markup(f'<span class="foto foto-inicial {classe}">{inicial}</span>')
